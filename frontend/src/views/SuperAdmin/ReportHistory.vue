<script setup>
import { computed, ref, watch } from 'vue'
import { useRoute } from 'vue-router'
import { getReportHistory } from '@/apis.js'
import AttendanceReport from '@/components/reporting/AttendanceReport.vue'
import PhysicalReport from '@/components/reporting/PhysicalReport.vue'
import ACCReport from '@/components/reporting/ACCReport.vue'

const props = defineProps({ reportType: String })
const route = useRoute()
const result = ref(null), loading = ref(false), error = ref('')
const title = computed(() => ({ attendance: 'attendance', physical: 'physical-test', acc: 'ACC' })[props.reportType])
const historyRoute = computed(() => `sa-${props.reportType}-history`)
const page = computed(() => Math.max(1, Number.parseInt(route.query.page, 10) || 1))
const dateTime = value => new Date(value).toLocaleString('en-NZ', { timeZone: 'Pacific/Auckland' })

watch(() => [props.reportType, route.params.id, page.value], async ([type, id, pageNumber], _, onCleanup) => {
  let current = true
  onCleanup(() => { current = false })
  result.value = null
  error.value = ''
  loading.value = true
  try {
    const data = await getReportHistory(type, { id, page: pageNumber })
    if (current) result.value = data
  } catch (e) {
    if (current) error.value = e.response?.data?.detail || 'Could not load saved reports. Please try again.'
  } finally { if (current) loading.value = false }
}, { immediate: true })
</script>

<template>
  <div class="dash-page"><main class="content">
    <RouterLink v-if="route.params.id" class="back-link" :to="{ name: historyRoute, params: { id: '' }, query: { page } }">← Past {{ title }} reports</RouterLink>
    <RouterLink v-else class="back-link" :to="{ name: `sa-${reportType}-report` }">← {{ title }} reporting</RouterLink>
    <p v-if="loading" class="loading-note" role="status">Loading saved reports…</p>
    <p v-else-if="error" class="form-error" role="alert">{{ error }}</p>
    <template v-else-if="result">
      <template v-if="route.params.id">
        <p class="page-subtitle">{{ result.branch_name }} · Generated {{ dateTime(result.created_at) }} (NZ time) · By {{ result.requested_by }}</p>
        <p class="loading-note">Statistics saved when this report was generated. The explanation includes any saved edits.</p>
        <component :is="({ attendance: AttendanceReport, physical: PhysicalReport, acc: ACCReport })[reportType]" :key="result.job_id" :saved-report="result" />
      </template>
      <template v-else>
        <div class="page-header"><h1>Past {{ title }} reports</h1></div>
        <p class="page-subtitle">Completed reports generated by all administrators, newest first. Dates and times are shown in NZ time.</p>
        <p v-if="!result.count" class="loading-note">No {{ title }} reports have been generated yet.</p>
        <div v-else class="table-scroll">
          <table class="data-table">
            <thead><tr><th>Reporting period</th><th>Scope</th><th>Generated</th><th>Generated by</th><th>Report</th></tr></thead>
            <tbody><tr v-for="report in result.results" :key="report.job_id">
              <td>{{ report.scope?.start_date }} to {{ report.scope?.end_date }}</td>
              <td>{{ report.branch_name }}</td><td>{{ dateTime(report.created_at) }}</td><td>{{ report.requested_by }}</td>
              <td><RouterLink :to="{ name: historyRoute, params: { id: report.job_id }, query: { page } }">Open report</RouterLink></td>
            </tr></tbody>
          </table>
        </div>
        <nav v-if="result.count" class="pagination" aria-label="Report history pages">
          <RouterLink v-if="result.previous" :to="{ name: historyRoute, query: { page: page - 1 } }">Previous</RouterLink>
          <span>Page {{ page }} · {{ result.count }} reports</span>
          <RouterLink v-if="result.next" :to="{ name: historyRoute, query: { page: page + 1 } }">Next</RouterLink>
        </nav>
      </template>
    </template>
  </main></div>
</template>

<style scoped>
.table-scroll { overflow-x: auto; }
.pagination { display: flex; align-items: center; gap: 20px; margin-top: 24px; }
</style>
